/** The language of a page, read from its path: /<base>/<lang>/... */
export const langFromPath = (pathname: string, base: string): Lang => {
    const first = pathname.slice(base.length).split('/').filter(Boolean)[0];
    return first === 'es' ? 'es' : 'en';
};
